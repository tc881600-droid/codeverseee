import React, { useRef } from 'react';
import { Download, BookOpen, ChevronRight } from 'lucide-react';
import html2pdf from 'html2pdf.js';
import { LANGUAGE_DOCS } from '../lib/languageDocs';

interface DocumentViewerProps {
  language: string;
}

export const DocumentViewer: React.FC<DocumentViewerProps> = ({ language }) => {
  const contentRef = useRef<HTMLDivElement>(null);
  const doc = LANGUAGE_DOCS[language];

  const handleDownloadPDF = () => {
    if (!contentRef.current) return;

    const element = contentRef.current;
    const opt: any = {
      margin: 10,
      filename: `${doc.title.replace(/\s+/g, '_')}.pdf`,
      image: { type: 'jpeg', quality: 0.98 },
      html2canvas: { scale: 2, useCORS: true },
      jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' }
    };

    html2pdf().from(element).set(opt).save();
  };

  if (!doc) {
    return (
      <div className="text-center py-12">
        <p className="text-gray-500">Documentation for this language is not available yet.</p>
      </div>
    );
  }

  return (
    <div className="max-w-6xl mx-auto">
      {/* Header with Download Button */}
      <div className="sticky top-0 z-10 bg-gradient-to-r from-indigo-600 to-purple-600 text-white p-6 rounded-t-lg shadow-lg">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <BookOpen className="w-8 h-8" />
            <div>
              <h1 className="text-3xl font-bold">{doc.title}</h1>
              <p className="text-indigo-100 mt-1">{doc.description}</p>
            </div>
          </div>
          <button
            onClick={handleDownloadPDF}
            className="flex items-center gap-2 bg-white text-indigo-600 px-6 py-3 rounded-lg font-semibold hover:bg-indigo-50 transition-colors shadow-md"
          >
            <Download className="w-5 h-5" />
            Download PDF
          </button>
        </div>
      </div>

      {/* Document Content */}
      <div
        ref={contentRef}
        className="bg-white p-8 md:p-12 shadow-xl"
        style={{
          fontFamily: 'Georgia, serif',
          lineHeight: '1.8',
          color: '#1a1a1a'
        }}
      >
        {/* Title Page */}
        <div className="text-center mb-12 pb-8 border-b-4 border-indigo-600">
          <h1 className="text-5xl font-bold text-indigo-600 mb-4">{doc.title}</h1>
          <p className="text-xl text-gray-600">{doc.description}</p>
          <p className="text-sm text-gray-500 mt-4">CodeVerse Learning Platform</p>
        </div>

        {/* Table of Contents */}
        <div className="mb-12 p-6 bg-gray-50 rounded-lg border-l-4 border-indigo-600">
          <h2 className="text-2xl font-bold mb-4 text-indigo-600">Table of Contents</h2>
          <ul className="space-y-2">
            {doc.chapters.map((chapter, idx) => (
              <li key={chapter.id} className="flex items-center gap-2">
                <ChevronRight className="w-4 h-4 text-indigo-600" />
                <span className="font-semibold">{chapter.title}</span>
              </li>
            ))}
          </ul>
        </div>

        {/* Chapters */}
        {doc.chapters.map((chapter, chapterIdx) => (
          <div key={chapter.id} className="mb-12 page-break-inside-avoid">
            <h2 className="text-3xl font-bold text-indigo-600 mb-6 pb-2 border-b-2 border-indigo-200">
              {chapter.title}
            </h2>

            {chapter.sections.map((section, sectionIdx) => (
              <div key={sectionIdx} className="mb-8">
                <h3 className="text-2xl font-bold text-gray-800 mb-4">
                  {section.title}
                </h3>

                <div className="text-gray-700 whitespace-pre-line mb-4">
                  {section.content}
                </div>

                {section.code && (
                  <div className="bg-gray-900 rounded-lg p-4 mb-4 overflow-x-auto">
                    <pre className="text-sm text-green-400 font-mono">
                      <code>{section.code}</code>
                    </pre>
                  </div>
                )}
              </div>
            ))}
          </div>
        ))}

        {/* Footer */}
        <div className="mt-12 pt-8 border-t-4 border-indigo-600 text-center text-gray-600">
          <p className="text-lg font-semibold">End of {doc.title}</p>
          <p className="text-sm mt-2">Generated by CodeVerse Learning Platform</p>
          <p className="text-xs mt-4 text-gray-500">
            © 2024 CodeVerse. All rights reserved.
          </p>
        </div>
      </div>

      {/* Bottom Download Button */}
      <div className="bg-gray-100 p-6 rounded-b-lg shadow-lg text-center">
        <button
          onClick={handleDownloadPDF}
          className="flex items-center gap-2 mx-auto bg-indigo-600 text-white px-8 py-4 rounded-lg font-semibold hover:bg-indigo-700 transition-colors shadow-md"
        >
          <Download className="w-5 h-5" />
          Download Complete Course as PDF
        </button>
      </div>
    </div>
  );
};
